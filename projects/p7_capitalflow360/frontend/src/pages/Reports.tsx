import { Alert, Box, Button, Card, CardContent, Grid, Typography } from "@mui/material";
import Download from "@mui/icons-material/Download";
import { useState } from "react";
import { api } from "../api";
import { ErrorAlert, PageHeader } from "../components/common";

const DECKS = [
  { file: "CF360_Executive_Summary.pptx", title: "Executive summary deck", who: "Leadership, 8-10 slides" },
  { file: "CF360_Business_Process_Walkthrough.pptx", title: "Business process walkthrough", who: "Operations and BA audience, 15-20 slides" },
  { file: "CF360_Test_Strategy_and_Results.pptx", title: "Test strategy and results", who: "QA and engineering, 12-15 slides" },
  { file: "CF360_Architecture_and_Data.pptx", title: "Architecture and data", who: "Engineering and data, 10-12 slides" },
  { file: "CapitalFlow360_Interview_and_Demonstration_Handbook.pdf", title: "Interview and demonstration handbook", who: "30-40 pages, 60+ Q&A" },
];

export default function Reports() {
  const [err, setErr] = useState<unknown>(null);
  const [ok, setOk] = useState(false);
  const snapshot = async () => {
    setErr(null);
    try {
      const data = await api("/reports/snapshot");
      const a = document.createElement("a");
      a.href = URL.createObjectURL(new Blob([JSON.stringify(data, null, 2)], { type: "application/json" }));
      a.download = "cf360_metrics_snapshot.json";
      a.click();
      setOk(true);
    } catch (e) {
      setErr(e);
    }
  };
  return (
    <Box>
      <PageHeader title="Reports" subtitle="Every deck and the handbook are built from one metrics snapshot, so the numbers agree everywhere."
        actions={<Button variant="contained" startIcon={<Download />} onClick={snapshot} data-testid="download-snapshot">Metrics snapshot (JSON)</Button>} />
      <ErrorAlert error={err} />
      {ok && <Alert severity="success" sx={{ mb: 2 }}>Snapshot downloaded.</Alert>}
      <Grid container spacing={2}>
        {DECKS.map((d) => (
          <Grid key={d.file} size={{ xs: 12, sm: 6, md: 4 }}>
            <Card><CardContent>
              <Typography fontWeight={700}>{d.title}</Typography>
              <Typography variant="body2" color="text.secondary" sx={{ mb: 1 }}>{d.who}</Typography>
              <Button size="small" href={`/reports/${d.file}`} target="_blank" data-testid={`report-${d.file}`}>Open {d.file.split(".").pop()?.toUpperCase()}</Button>
            </CardContent></Card>
          </Grid>
        ))}
      </Grid>
      <Typography variant="caption" color="text.secondary" sx={{ display: "block", mt: 2 }}>Report files are generated by reporting/build_reports.py and served from /reports when present.</Typography>
    </Box>
  );
}
