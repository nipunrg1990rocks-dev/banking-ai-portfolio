"""Generate the reference docs from the code and data they describe, so they cannot drift.

    python scripts/build_docs.py

Writes docs/rule_catalogue.md (from cf360.rules.catalogue), docs/lifecycle_matrix.md (from the
hand-written lifecycle spec in testkit/oracle/specs.py) and docs/data_dictionary.md (from data/manifest.json).
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "backend"), str(ROOT)]
DOCS = ROOT / "docs"


def cell(x) -> str:
    return str(x if x not in (None, "") else "-").replace("|", "\\|").replace("\n", " ")


def md_table(head, rows) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def rule_catalogue() -> str:
    from cf360.rules.catalogue import RULES
    cases = json.loads((ROOT / "testkit" / "out" / "cases.json").read_text())
    trace = Counter(r for c in cases for r in c["rule_ids"])
    fam = Counter(r["family"] for r in RULES)
    parts = ["# CapitalFlow 360: business rule catalogue", "",
             "Generated by `scripts/build_docs.py` from `backend/cf360/rules/catalogue.py`; do not edit by hand.",
             f"{len(RULES)} rules in {len(fam)} families. \"Cases\" counts generated test cases that name the rule "
             f"({sum(1 for r in RULES if trace[r['id']])} of {len(RULES)} rules have at least one).",
             "Rules marked *simplified* follow a market convention in a reduced form suitable for a simulation; none is a claim of regulatory compliance.", "",
             md_table(["Family", "Rules"], sorted(fam.items())), ""]
    for f in sorted(fam):
        parts += [f"## {f}", ""]
        for r in [r for r in RULES if r["family"] == f]:
            parts += [f"### {r['id']}: {r['name']}{' (simplified)' if r.get('simplification') else ''}", "",
                      md_table(["Field", "Value"], [["Rationale", r["rationale"]], ["Products", r["products"]], ["Inputs", r["inputs"]],
                                                    ["Formula", r["formula"]], ["Boundaries", r["boundaries"]], ["Tolerance", r["tolerance"]],
                                                    ["Expected output", r["expected_output"]], ["Error code", r["error_code"]],
                                                    ["Source", r["source"]], ["Generated cases", trace[r["id"]]]]), ""]
    return "\n".join(parts)


def lifecycle_matrix() -> str:
    from testkit.oracle import specs
    states = ["CAPTURED", "ENRICHED", "ALLOCATED", "CONFIRMED", "CLEARED", "INSTRUCTED", "PARTIALLY_SETTLED", "SETTLEMENT_FAILED",
              "SETTLED", "OPEN", "EXERCISED", "EXPIRED", "MATURED", "CLOSED", "CANCELLED"]
    parts = ["# CapitalFlow 360: lifecycle matrix", "",
             "Generated by `scripts/build_docs.py` from the hand-written spec in `testkit/oracle/specs.py`; do not edit by hand.",
             "Each product's allowed status moves. Every listed edge is tested to succeed and every other edge to be refused (HTTP 409).", ""]
    groups: dict[frozenset, list[str]] = {}
    for prod, edges in specs.LIFECYCLE.items():
        groups.setdefault(frozenset(edges), []).append(prod)
    for edges, prods in groups.items():
        used = [s for s in states if any(s in e for e in edges)] + sorted({s for e in edges for s in e} - set(states))
        rows = [[f"**{a}**"] + ["yes" if (a, b) in edges else "" for b in used] for a in used if any(x == a for x, _ in edges)]
        parts += [f"## {', '.join(sorted(prods))}", "", f"{len(edges)} allowed moves. Rows are the current status, columns the next status.", "",
                  md_table(["From \\ To"] + used, rows), ""]
    return "\n".join(parts)


def data_dictionary() -> str:
    m = json.loads((ROOT / "data" / "manifest.json").read_text())
    parts = ["# CapitalFlow 360: data dictionary", "",
             "Generated by `scripts/build_docs.py` from `data/manifest.json`; do not edit by hand. All data is synthetic.",
             f"Seed {m['generator_seed']}; opening date {m['opening_date']}; statement date {m['statement_date']}; "
             f"{m['baseline_trade_count']} baseline trades.", "",
             md_table(["Workbook", "Sheets", "Rows", "SHA-256 (first 12)"],
                      [[f, ", ".join(v["rows"]), sum(v["rows"].values()), v["sha256"][:12]] for f, v in m["files"].items()]), "",
             "Negative files (kept apart from the baseline; every row labelled with the rule and layer that should catch it):", "",
             md_table(["File", "Rows"], [[f, sum(v["rows"].values())] for f, v in m["negative_files"].items()]), ""]
    for f, v in m["files"].items():
        for sheet, cols in (v.get("schema") or {}).items():
            parts += [f"## {f} / {sheet}", "", md_table(["Column", "Type", "Nullable"], [[c["column"], c["type"], "yes" if c["nullable"] else "no"] for c in cols]), ""]
    return "\n".join(parts)


if __name__ == "__main__":
    for name, fn in [("rule_catalogue.md", rule_catalogue), ("lifecycle_matrix.md", lifecycle_matrix), ("data_dictionary.md", data_dictionary)]:
        (DOCS / name).write_text(fn())
        print("wrote", DOCS / name)
